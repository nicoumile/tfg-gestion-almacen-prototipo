GRIS = "#b9bdc7"


def svg(clave, tam=128, ganada=True, titulo=None):
    """La figurita como SVG (texto). Bloqueada: silueta gris."""
    filas = SPRITES[clave]
    rects = []
    for y, fila in enumerate(filas):
        x = 0
        while x < len(fila):
            c = fila[x]
            if c == ".":
                x += 1
                continue
            largo = 1
            while x + largo < len(fila) and fila[x + largo] == c:
                largo += 1
            color = PALETA.get(c, "#262730") if ganada else GRIS
            rects.append(f'<rect x="{x}" y="{y}" width="{largo}" height="1" fill="{color}"/>')
            x += largo
    etiqueta = titulo or clave
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="{tam}" height="{tam}" '
            f'shape-rendering="crispEdges" role="img" aria-label="{etiqueta}">' + "".join(rects) + "</svg>")
